//! Dependency-free MD5, SHA-1 and SHA-256 digests.
//!
//! The crate is deliberately tiny and self-contained: the shell's `md5sum`,
//! `sha1sum` and `sha256sum` builtins only need a digest of an in-memory buffer,
//! and adding a crypto dependency for that would violate the workspace's
//! "std only" rule.

/// Which digest to compute.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Algorithm {
    Md5,
    Sha1,
    Sha256,
}

impl Algorithm {
    /// Lower-case hex digest of `data`.
    pub fn hex_digest(self, data: &[u8]) -> String {
        match self {
            Algorithm::Md5 => to_hex(&md5(data)),
            Algorithm::Sha1 => to_hex(&sha1(data)),
            Algorithm::Sha256 => to_hex(&sha256(data)),
        }
    }
}

fn to_hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(char::from_digit((byte >> 4) as u32, 16).unwrap_or('0'));
        out.push(char::from_digit((byte & 0xf) as u32, 16).unwrap_or('0'));
    }
    out
}

/// Pad a message the way MD5/SHA-1/SHA-256 do: a `0x80` byte, zeros, then the
/// bit length as a big-endian integer.
fn pad(message: &[u8], length_bytes: usize, little_endian_length: bool) -> Vec<u8> {
    let mut padded = message.to_vec();
    padded.push(0x80);
    while padded.len() % 64 != 56 {
        padded.push(0);
    }
    let bits = (message.len() as u64).wrapping_mul(8);
    let length = if little_endian_length {
        bits.to_le_bytes().to_vec()
    } else {
        bits.to_be_bytes().to_vec()
    };
    // MD5 uses a 64-bit little-endian length; SHA-1/256 a 64-bit big-endian one.
    padded.extend_from_slice(&length[..length_bytes]);
    padded
}

