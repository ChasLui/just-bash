#!/usr/bin/env node

/**
 * Generates terminal-content.ts from the main repo files.
 * Run this before build to update the embedded content.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(__dirname, "../../../packages/just-bash");
const rustCoreDir = path.resolve(__dirname, "../../../packages/just-bash/rust-core");
const outputFile = path.resolve(__dirname, "../app/components/terminal-content.ts");

// Read just-bash package files
const license = fs.readFileSync(path.join(packageDir, "LICENSE"), "utf-8");
const wtfIsThis = fs.readFileSync(path.resolve(__dirname, "../README.md"), "utf-8");

const cargoToml = fs.readFileSync(path.join(rustCoreDir, "Cargo.toml"), "utf-8");
const cargoMatch = cargoToml.match(/^version\s*=\s*"([^"]+)"/m);
const version = cargoMatch ? cargoMatch[1] : "3.0.0";

const readme = `# just-bash

Core runtime is now implemented in Rust under 'packages/just-bash/rust-core':

- Crate: 'just-bash'
- CLI binary: 'just-bash-rs'
- Legacy TypeScript implementation remains in 'packages/just-bash/legacy-ts' for historical reference.

Use Rust tooling for active development:

- cargo test --workspace
- cargo build --workspace
- cargo run -p just-bash --bin just-bash-rs -- "echo hello from rust"

## Optional companion

@just-bash/executor is an optional companion package for host tool invocation patterns
(for example js-exec) and is not required for the Rust core runtime.
`;

const agentsMd = `# AGENTS.md - just-bash

This file is provided for historical TypeScript-facing guidance only.
The active runtime is Rust-first in packages/just-bash/rust-core (just-bash-rs).
Use this content as legacy reference; install examples here do not reflect the active runtime path.

If your workflow depends on the JS API, this doc may still be useful as a reference.
`;

const simplifiedPackageJson = JSON.stringify(
  {
    name: "just-bash",
    version,
    description: "Rust core for the just-bash virtual shell",
    homepage: "https://github.com/vercel-labs/just-bash",
    license: "Apache-2.0",
  },
  null,
  2,
);

// Escape backticks and ${} for template literals
function escapeTemplate(str) {
  return str
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

const content = `// Auto-generated by scripts/generate-terminal-content.mjs
// Do not edit manually - run "node ../scripts/generate-terminal-content.mjs" to regenerate

export const version = "${version}";

// Command outputs
export const CMD_ABOUT = \`just-bash v\${version}
A Rust-first sandboxed bash runtime with an in-memory filesystem.
Designed for AI agents needing a secure, sandboxed environment.

Custom commands:
  about       About just-bash
  install     Installation instructions
  github      GitHub repository

Or try any bash command: ls, cat, echo, grep, awk, jq, sed, etc.
Type 'help' for a list of all built-in commands.
\`;

export const CMD_INSTALL = \`# Install and run from source (Rust core)

Usage:
  # Build Rust runtime (from repo root):
  cargo build -p just-bash --bin just-bash-rs

  # Run once with cargo:
  cargo run -p just-bash --bin just-bash-rs -- "echo hello"
\`;

export const CMD_GITHUB = "https://github.com/vercel-labs/just-bash\\n";

// File contents (generated from repo)
export const FILE_README = \`${escapeTemplate(readme)}\`;

export const FILE_LICENSE = \`${escapeTemplate(license)}\`;

export const FILE_PACKAGE_JSON = \`${escapeTemplate(simplifiedPackageJson)}\`;

export const FILE_AGENTS_MD = \`${escapeTemplate(agentsMd)}\`;

export const FILE_WTF_IS_THIS = \`${escapeTemplate(wtfIsThis)}\`;
`;

fs.writeFileSync(outputFile, content);
console.log(`Generated ${outputFile}`);
